#!/usr/bin/env bash
#
# Install WordPress core and the core PHPUnit test library for the integration
# suite, from GitHub mirrors rather than wordpress.org so it works behind
# egress policies that block the latter.
#
# Usage: bin/install-wp-tests.sh [wp-version] [tests-dir] [core-dir]
#
#   wp-version  Git tag on github.com/WordPress/WordPress (default: latest)
#   tests-dir   Where the test library lands (default: /tmp/wordpress-tests-lib)
#   core-dir    Where WordPress core lands (default: /tmp/wordpress)
#
# Database connection comes from the environment (defaults in brackets):
#   WP_TESTS_DB_NAME [wordpress_test]  WP_TESTS_DB_USER [wp]
#   WP_TESTS_DB_PASS [wp]              WP_TESTS_DB_HOST [127.0.0.1]
#
# Safe to re-run: existing checkouts are reused.

set -euo pipefail

WP_VERSION="${1:-latest}"
TESTS_DIR="${2:-/tmp/wordpress-tests-lib}"
CORE_DIR="${3:-/tmp/wordpress}"

DB_NAME="${WP_TESTS_DB_NAME:-wordpress_test}"
DB_USER="${WP_TESTS_DB_USER:-wp}"
DB_PASS="${WP_TESTS_DB_PASS:-wp}"
DB_HOST="${WP_TESTS_DB_HOST:-127.0.0.1}"

if [ "$WP_VERSION" = "latest" ]; then
	WP_VERSION="$(git ls-remote --tags https://github.com/WordPress/WordPress \
		| grep -oE 'refs/tags/[0-9]+\.[0-9]+(\.[0-9]+)?$' \
		| sed 's#refs/tags/##' | sort -V | tail -1)"
fi

# wordpress-develop tags always carry three components; WordPress tags drop a
# trailing .0 for x.y releases.
DEVELOP_TAG="$WP_VERSION"
if [[ "$DEVELOP_TAG" =~ ^[0-9]+\.[0-9]+$ ]]; then
	DEVELOP_TAG="${DEVELOP_TAG}.0"
fi

echo "WordPress ${WP_VERSION} (develop tag ${DEVELOP_TAG})"

if [ ! -f "$CORE_DIR/wp-includes/version.php" ]; then
	echo "Cloning WordPress core into $CORE_DIR"
	git clone -q --depth 1 --branch "$WP_VERSION" https://github.com/WordPress/WordPress "$CORE_DIR"
else
	echo "Core already present at $CORE_DIR"
fi

DEVELOP_DIR="${TESTS_DIR}-develop"
if [ ! -d "$DEVELOP_DIR/tests/phpunit/includes" ]; then
	echo "Cloning the test library into $DEVELOP_DIR"
	git clone -q --depth 1 --branch "$DEVELOP_TAG" --filter=blob:none --sparse \
		https://github.com/WordPress/wordpress-develop "$DEVELOP_DIR"
	git -C "$DEVELOP_DIR" sparse-checkout set tests/phpunit/includes tests/phpunit/data
else
	echo "Test library already present at $DEVELOP_DIR"
fi

mkdir -p "$TESTS_DIR"
ln -sfn "$DEVELOP_DIR/tests/phpunit/includes" "$TESTS_DIR/includes"
ln -sfn "$DEVELOP_DIR/tests/phpunit/data" "$TESTS_DIR/data"

cat > "$TESTS_DIR/wp-tests-config.php" <<PHP
<?php
/* Generated by bin/install-wp-tests.sh. Edit the script, not this file. */
define( 'ABSPATH', '${CORE_DIR}/' );
define( 'WP_DEFAULT_THEME', 'default' );
define( 'WP_TESTS_FORCE_KNOWN_BUGS', false );
define( 'WP_DEBUG', true );

define( 'DB_NAME', '${DB_NAME}' );
define( 'DB_USER', '${DB_USER}' );
define( 'DB_PASSWORD', '${DB_PASS}' );
define( 'DB_HOST', '${DB_HOST}' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );

\$table_prefix = 'wptests_';

define( 'WP_TESTS_DOMAIN', 'example.org' );
define( 'WP_TESTS_EMAIL', 'admin@example.org' );
define( 'WP_TESTS_TITLE', 'ODSI Test Site' );
define( 'WP_PHP_BINARY', 'php' );
define( 'WPLANG', '' );
PHP

echo "Test library ready at $TESTS_DIR"
